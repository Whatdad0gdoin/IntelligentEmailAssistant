def _path(kind, model, *parts, ext="csv"):
    name = "_".join([kind, model, *[p for p in parts if p]]) + f".{ext}"
    return os.path.join(OUT_DIR, name)


def _refuse_overwrite(paths, force):
    existing = [p for p in paths if os.path.exists(p)]
    if existing and not force:
        sys.exit("Refusing to overwrite existing results (use a new --tag, or --force):\n  "
                 + "\n  ".join(os.path.relpath(p, ROOT) for p in existing))


def _config():
    return Config(require_llm=False, require_auth=False)


def _write_calls(path, records, **extra):
    with open(path, "w", encoding="utf-8") as f:
        for record in records:
            record.update(extra)
            f.write(json.dumps(record) + "\n")


# --- classify -----------------------------------------------------------------

def _review_reason(raw, source, threshold):
    """Why the verifier routed a label to Review, recomputed from the raw answer."""
    if raw is None:
        return "missing_from_model_response"
    if raw.get("category") not in CATEGORIES:
        return "category_outside_enum"
    if not verify_evidence((raw.get("evidence") or "").strip(), source):
        return "evidence_not_in_source"
    try:
        confidence = float(raw.get("confidence"))
    except (TypeError, ValueError):
        confidence = 0.0
    if confidence < threshold:
        return "low_confidence"
    return ""


def mask_id(row_id):
    """An opaque id with no provenance in it.

    Dataset ids are '<provenance>-<sha>' -- 'generated-…' for every Studies
    row -- and classify_user() puts the id into the prompt, which hands the
    model a cue production never has. Same length and alphabet for every row.
    """
    import hashlib
    return "m" + hashlib.sha1(row_id.encode("utf-8")).hexdigest()[:12]


def run_classify(model, split, tag, force, batch_size=BATCH_SIZE, run_name=None,
                 mask_ids=False, extra_settings=None):
    """One classification run. `run_name` names the files ('<model>+<variant>')."""
    config = _config()
    rows = load_classify_rows(DATASET, None, split)
    name = run_name or model
    out_csv = _path("classify", name, split, tag)
    out_calls = _path("calls", name, "classify", split, tag, ext="jsonl")
    _refuse_overwrite([out_csv, out_calls], force)

    adapter = providers.build(model)
    set_client(adapter)
    calls, saved = [], []
    started = time.perf_counter()
    try:
        for index in range(0, len(rows), batch_size):
            batch = rows[index:index + batch_size]
            sent_id = {r["id"]: (mask_id(r["id"]) if mask_ids else r["id"]) for r in batch}
            real_id = {v: k for k, v in sent_id.items()}
            items = [{"id": sent_id[r["id"]], "subject": r["subject"], "body": r["body"],
                      "sender": r.get("sender", "")} for r in batch]
            results, failures = None, 0
            for attempt in range(1 + BATCH_REATTEMPTS):
                adapter.last_payload = None
                try:
                    results = classify_emails(items, config, session_key=None, user=None,
                                              use_cache=False)
                    break
                except Exception as exc:  # the call failed even after client.py-style retry
                    failures += 1
                    print(f"  batch {index // batch_size}: {type(exc).__name__}, "
                          f"re-attempt {attempt + 1}/{BATCH_REATTEMPTS}", flush=True)
                    time.sleep(REATTEMPT_WAIT_SECONDS)
            for record in adapter.drain():
                record.update(batch=index // batch_size, batch_failures_before=failures)
                calls.append(record)

            raw_by_id = {}
            if results is not None:
                for raw in (adapter.last_payload or {}).get("results", []) or []:
                    if isinstance(raw, dict) and raw.get("id") not in raw_by_id:
                        raw_by_id[raw.get("id")] = raw
            by_id = {r["id"]: r for r in (results or [])}
            for row in batch:
                result = by_id.get(sent_id[row["id"]])
                raw = raw_by_id.get(sent_id[row["id"]])
                source = row["subject"] + "\n" + preprocess(row["body"], config.token_budget_chars).text
                if result is None:
                    predicted, reason = REVIEW_CATEGORY, "call_failed"
                else:
                    predicted = result["category"]
                    reason = (_review_reason(raw, source, config.classify_confidence_threshold)
                              if predicted == REVIEW_CATEGORY else "")
                saved.append({
                    "id": row["id"], "split": split, "provenance": row["provenance"],
                    "text_origin": row["text_origin"], "label_source": row["label_source"],
                    "expected": row["category"], "predicted": predicted,
                    "correct": row["category"] == predicted,
                    "raw_category": (raw or {}).get("category", ""),
                    "raw_confidence": (raw or {}).get("confidence", ""),
                    "evidence_ok": "" if raw is None else
                        verify_evidence(((raw or {}).get("evidence") or "").strip(), source),
                    "reason": reason,
                    "batch": index // batch_size,
                    "subject": row["subject"][:120],
                })
            print(f"  {name} {split}: {min(index + batch_size, len(rows))}/{len(rows)}", flush=True)
    finally:
        reset_client()

    with open(out_csv, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(saved[0].keys()))
        writer.writeheader()
        writer.writerows(saved)
    settings = adapter.describe()
    settings.update(batch_size=batch_size, mask_ids=mask_ids, **(extra_settings or {}))
    _write_calls(out_calls, calls, task="classify", split=split, tag=tag, settings=settings)
    metrics = _score([(r["expected"], r["predicted"]) for r in saved])
    print(f"{name} {split} {tag}: n={metrics['n']} coverage={metrics['coverage']:.1%} "
          f"accuracy={metrics['accuracy']:.1%} strict={metrics['strict']:.1%} "
          f"macroF1={metrics['macro_f1']:.3f}  ({time.perf_counter() - started:.0f}s)")


# --- intent ---------------------------------------------------------------------

def run_intent(model, tag, force):
    from backend.orchestrator.intent import classify_intent
    from eval.intent_harness import GRADED, UNKNOWN_PROBES, load

    config = _config()
    out_csv = _path("intent", model, tag)
    out_calls = _path("calls", model, "intent", tag, ext="jsonl")
    _refuse_overwrite([out_csv, out_calls], force)

    adapter = providers.build(model)
    set_client(adapter)
    saved, calls = [], []
    try:
        for set_name, path in (("graded", GRADED), ("probe", UNKNOWN_PROBES)):
            for row in load(path):
                error, intent, confidence = "", "", ""
                try:
                    result = classify_intent(row["transcript"], config)
                    intent, confidence = result["intent"], result["confidence"]
                except Exception as exc:
                    error = type(exc).__name__
                calls.extend(adapter.drain())
                saved.append({"set": set_name, "transcript": row["transcript"],
                              "expected": row["expected_intent"], "actual": intent,
                              "confidence": confidence, "error": error})
    finally:
        reset_client()

    with open(out_csv, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(saved[0].keys()))
        writer.writeheader()
        writer.writerows(saved)
    _write_calls(out_calls, calls, task="intent", tag=tag, settings=adapter.describe())
    graded = [r for r in saved if r["set"] == "graded"]
    probes = [r for r in saved if r["set"] == "probe"]
    print(f"{model} intent {tag}: graded {sum(r['actual'] == r['expected'] for r in graded)}/"
          f"{len(graded)}, probes {sum(r['actual'] == r['expected'] for r in probes)}/{len(probes)}")


