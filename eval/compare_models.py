def run_memory():
    """Client-side footprint of each SDK: import, construct, one free metadata call.

    Measured in a fresh interpreter per SDK so they cannot share imports. The
    call is models.list(), which costs nothing and initialises the HTTP and TLS
    stack the same way a completion would.
    """
    results = {}
    for name, code in _MEMORY_PROBES.items():
        script = (
            "import os, psutil, time\n"
            "from dotenv import load_dotenv\n"
            f"load_dotenv({os.path.join(ROOT, 'backend', '.env')!r})\n"
            "p = psutil.Process(); base = p.memory_info().rss\n"
            "t = time.perf_counter()\n"
            f"{code}\n"
            "print(base, p.memory_info().rss, time.perf_counter() - t)\n"
        )
        samples = []
        for _ in range(3):
            out = subprocess.run([sys.executable, "-c", script], capture_output=True,
                                 text=True, timeout=120)
            if out.returncode != 0:
                samples = None
                print(f"{name}: failed: {out.stderr.strip()[-300:]}")
                break
            base, after, seconds = out.stdout.split()
            samples.append((int(base), int(after), float(seconds)))
        if samples:
            results[name] = {
                "interpreter_mb": statistics.median(s[0] for s in samples) / 2**20,
                "rss_after_mb": statistics.median(s[1] for s in samples) / 2**20,
                "delta_mb": statistics.median(s[1] - s[0] for s in samples) / 2**20,
                "cold_start_s": statistics.median(s[2] for s in samples),
            }
            print(f"{name:13} +{results[name]['delta_mb']:.1f} MB  "
                  f"(process {results[name]['rss_after_mb']:.1f} MB), "
                  f"import+first call {results[name]['cold_start_s']:.2f}s")
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, "memory.json"), "w", encoding="utf-8") as f:
        json.dump(results, f, indent=2)


