def _read_csv(path):
    with open(path, encoding="utf-8") as f:
        return list(csv.DictReader(f))


def _read_jsonl(path):
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def _wilson(k, n, z=1.96):
    if not n:
        return (0.0, 0.0)
    p = k / n
    denom = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / denom
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / denom
    return (centre - half, centre + half)


def _mcnemar(a_right, b_right):
    """Exact two-sided McNemar test on paired right/wrong outcomes.

    Only the discordant pairs carry information: rows one model got right and
    the other got wrong. Returns (only_a, only_b, p_value).
    """
    only_a = sum(1 for x, y in zip(a_right, b_right) if x and not y)
    only_b = sum(1 for x, y in zip(a_right, b_right) if y and not x)
    n = only_a + only_b
    if n == 0:
        return only_a, only_b, 1.0
    k = min(only_a, only_b)
    tail = sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n
    return only_a, only_b, min(1.0, 2 * tail)


def _pct(values, q):
    values = sorted(values)
    if not values:
        return float("nan")
    index = max(0, min(len(values) - 1, math.ceil(q * len(values)) - 1))
    return values[index]


def _call_stats(records):
    ok = [r for r in records if r.get("ok")]
    return {
        "calls": len(records),
        "failed": sum(1 for r in records if not r.get("ok")),
        "retried": sum(1 for r in records if r.get("attempts", 1) > 1),
        "unparseable": sum(r.get("unparseable", 0) for r in records),
        "refused": sum(1 for r in records if r.get("refused")),
        "p50_s": statistics.median([r["seconds"] for r in ok]) if ok else float("nan"),
        "p95_s": _pct([r["seconds"] for r in ok], 0.95),
        "input_tokens": sum(r.get("input_tokens", 0) for r in records),
        "output_tokens": sum(r.get("output_tokens", 0) for r in records),
        "thinking_tokens": sum(r.get("thinking_tokens", 0) for r in records),
    }


def _base(model):
    """The priced model behind a run name. Experiment variants are named
    '<model>+<variant>' (eval/experiments/), and cost what their model costs."""
    return model.split("+", 1)[0]


def _cost(model, input_tokens, output_tokens):
    return providers.cost_usd(_base(model), input_tokens, output_tokens)


def build_report():
    lines = []
    out = lines.append
    classify_files = sorted(glob.glob(os.path.join(OUT_DIR, "classify_*.csv")))
    runs = {}
    for path in classify_files:
        name = os.path.basename(path)[len("classify_"):-4]
        model, split, tag = name.rsplit("_", 2)
        runs[(model, split, tag)] = _read_csv(path)
    models = sorted({k[0] for k in runs}, key=lambda m: (m != BASELINE, m))

    def calls_for(model, task, *parts):
        path = _path("calls", model, task, *parts, ext="jsonl")
        return _read_jsonl(path) if os.path.exists(path) else []

    out("# Model comparison — measured\n")
    out("Generated by `python -m eval.compare_models report` from the files in "
        "`eval/data/compare/`, with no model call. Every figure recomputes from those files.\n")

    # Settings
    out("## Settings each model ran under\n")
    out("| Model | Provider | Settings | Price in / out per 1M (USD) |")
    out("|---|---|---|---|")
    for model in models:
        records = calls_for(model, "classify", "test", "r1") or calls_for(model, "classify", "dev", "r1")
        settings = (records[0].get("settings") if records else {}) or {}
        hidden = {"provider", "model"}
        if settings.get("reasoning_effort"):
            hidden.add("temperature")  # never sent to a reasoning model (eval/providers.py)
        shown = ", ".join(f"{k}={v}" for k, v in settings.items()
                          if k not in hidden and v is not None)
        price = providers.PRICES.get(_base(model))
        note = providers.PRICE_NOTES.get(_base(model), "")
        out(f"| {model} | {settings.get('provider', '?')} | {shown or '-'} | "
            f"{price[0]:.2f} / {price[1]:.2f}{' — ' + note if note else ''} |")
    out("")

    # FR-02 table
    for split in ("dev", "test"):
        out(f"## FR-02 categorisation — {split} split, run r1\n")
        out("| Model | n | Coverage | Accuracy | Strict (95% CI) | Macro-F1 | Real-only accuracy | "
            "Raw accuracy (before verifier) | Quote failed | Low conf. | Dropped |")
        out("|---|---|---|---|---|---|---|---|---|---|---|")
        for model in models:
            rows = runs.get((model, split, "r1"))
            if not rows:
                continue
            m = _score([(r["expected"], r["predicted"]) for r in rows])
            real = _score([(r["expected"], r["predicted"]) for r in rows if r["text_origin"] == "real"])
            with_raw = [r for r in rows if r["raw_category"]]
            raw_acc = sum(r["raw_category"] == r["expected"] for r in with_raw) / max(1, len(with_raw))
            strict_k = sum(r["expected"] == r["predicted"] for r in rows)
            lo, hi = _wilson(strict_k, len(rows))
            reasons = collections.Counter(r["reason"] for r in rows)
            out(f"| {model} | {m['n']} | {m['coverage']:.1%} | {m['accuracy']:.1%} | "
                f"{m['strict']:.1%} ({lo:.1%}–{hi:.1%}) | {m['macro_f1']:.3f} | "
                f"{real['accuracy']:.1%} | {raw_acc:.1%} | {reasons['evidence_not_in_source']} | "
                f"{reasons['low_confidence']} | "
                f"{reasons['missing_from_model_response'] + reasons['call_failed']} |")
        out("")

    # Paired comparisons vs baseline, per split
    for split in ("dev", "test"):
        base_rows = runs.get((BASELINE, split, "r1"))
        if not base_rows:
            continue
        out(f"## Paired comparison against {BASELINE} on the same {split} rows (strict correctness)\n")
        out("McNemar exact test on the discordant rows. A p-value above 0.05 means this "
            f"{split} split cannot distinguish the two; it does not mean they are equal.\n")
        out(f"| Model | Strict | Δ strict vs {BASELINE} | Rows only {BASELINE} got right | "
            "Rows only this one got right | p |")
        out("|---|---|---|---|---|---|")
        base_right = {r["id"]: r["expected"] == r["predicted"] for r in base_rows}
        for model in models:
            rows = runs.get((model, split, "r1"))
            if not rows or model == BASELINE:
                continue
            ids = [r["id"] for r in rows if r["id"] in base_right]
            mine = {r["id"]: r["expected"] == r["predicted"] for r in rows}
            a = [base_right[i] for i in ids]
            b = [mine[i] for i in ids]
            only_base, only_model, p = _mcnemar(a, b)
            delta = (sum(b) - sum(a)) / max(1, len(ids))
            out(f"| {model} | {sum(b) / len(ids):.1%} | {delta * 100:+.1f} pts | {only_base} | "
                f"{only_model} | {p:.3f} |")
        out("")
    base = runs.get((BASELINE, "test", "r1"))

    # Harness fidelity vs run 10
    if base and os.path.exists(RUN10):
        run10 = {r["id"]: r for r in _read_csv(RUN10)}
        same = [r for r in base if r["id"] in run10]
        agree = sum(r["predicted"] == run10[r["id"]]["predicted"] for r in same)
        m10 = _score([(run10[r["id"]]["expected"], run10[r["id"]]["predicted"]) for r in same])
        mb = _score([(r["expected"], r["predicted"]) for r in same])
        out("## Harness check: this harness's gpt-4o-mini run against the committed run 10\n")
        out(f"Same model, prompt, rows and batches; run 10 went through `client.py`, this run "
            f"through `eval/providers.py`. Labels agree on {agree}/{len(same)} rows "
            f"({agree / max(1, len(same)):.1%}). Strict: run 10 {m10['strict']:.1%}, this run "
            f"{mb['strict']:.1%}; accuracy: run 10 {m10['accuracy']:.1%}, this run "
            f"{mb['accuracy']:.1%}.\n")

    # Repeatability
    repeat_models = [m for m in models if (m, "test", "r2") in runs and (m, "test", "r1") in runs]
    if repeat_models:
        out("## Repeatability: the same test run twice (r1, r2)\n")
        out("| Model | Labels identical across runs | Strict r1 | Strict r2 | Spread (pts) |")
        out("|---|---|---|---|---|")
        for model in repeat_models:
            r1 = {r["id"]: r for r in runs[(model, "test", "r1")]}
            r2 = {r["id"]: r for r in runs[(model, "test", "r2")]}
            ids = [i for i in r1 if i in r2]
            same = sum(r1[i]["predicted"] == r2[i]["predicted"] for i in ids)
            s1 = sum(r1[i]["expected"] == r1[i]["predicted"] for i in ids) / len(ids)
            s2 = sum(r2[i]["expected"] == r2[i]["predicted"] for i in ids) / len(ids)
            out(f"| {model} | {same}/{len(ids)} ({same / len(ids):.1%}) | {s1:.1%} | {s2:.1%} | "
                f"{abs(s1 - s2) * 100:.1f} |")
        out("")

    # Cost, tokens, latency, reliability
    out("## Cost, tokens, latency and reliability (classification calls, all runs)\n")
    out("| Model | Calls | Failed after retry | Retried | Unparseable | Refused | "
        "Input tok / email | Output tok / email (thinking) | p50 / p95 s per 20-email call | "
        "USD per 1,000 emails |")
    out("|---|---|---|---|---|---|---|---|---|---|")
    per_op_cost = collections.defaultdict(dict)
    for model in models:
        records, emails = [], 0
        for (m, split, tag), rows in runs.items():
            if m == model:
                records += calls_for(model, "classify", split, tag)
                emails += len(rows)
        if not records:
            continue
        s = _call_stats(records)
        cost = _cost(model, s["input_tokens"], s["output_tokens"])
        per_op_cost[model]["classify"] = cost / max(1, emails)
        out(f"| {model} | {s['calls']} | {s['failed']} | {s['retried']} | {s['unparseable']} | "
            f"{s['refused']} | {s['input_tokens'] / max(1, emails):.0f} | "
            f"{s['output_tokens'] / max(1, emails):.0f} ({s['thinking_tokens'] / max(1, emails):.0f}) | "
            f"{s['p50_s']:.1f} / {s['p95_s']:.1f} | ${cost / max(1, emails) * 1000:.2f} |")
    out("\nThinking tokens are reported separately by OpenAI and Google; Anthropic bills "
        "them inside output tokens without a separate count, so that column reads 0 for "
        "Claude even where the model thought.\n")

    # Intent
    intent_files = sorted(glob.glob(os.path.join(OUT_DIR, "intent_*.csv")))
    if intent_files:
        out("## FR-05 voice intent (30 graded transcripts + 8 out-of-scope probes)\n")
        out("Same transcripts and scoring as `eval/intent_harness.py`: on the graded 30 an "
            "`unknown` is a miss; on the probes it is the only correct answer. The prompt is "
            "the shipped INTENT_SYSTEM, unchanged — FIXES.md item 5's prompt gap affects every model.\n")
        out("| Model | Graded accuracy (95% CI) | Wrong dispatches | Declined | Probes correct | "
            "p50 / p95 s per call | USD per command |")
        out("|---|---|---|---|---|---|---|")
        for path in intent_files:
            model, tag = os.path.basename(path)[len("intent_"):-4].rsplit("_", 1)
            rows = _read_csv(path)
            graded = [r for r in rows if r["set"] == "graded"]
            probes = [r for r in rows if r["set"] == "probe"]
            right = sum(r["actual"] == r["expected"] for r in graded)
            wrong = sum(1 for r in graded if r["actual"] not in ("unknown", "", r["expected"]))
            declined = sum(1 for r in graded if r["actual"] == "unknown")
            lo, hi = _wilson(right, len(graded))
            s = _call_stats(calls_for(model, "intent", tag))
            cost = _cost(model, s["input_tokens"], s["output_tokens"]) / max(1, s["calls"])
            per_op_cost[model]["voice_command"] = cost
            out(f"| {model} | {right}/{len(graded)} = {right / len(graded):.1%} "
                f"({lo:.0%}–{hi:.0%}) | {wrong} | {declined} | "
                f"{sum(r['actual'] == r['expected'] for r in probes)}/{len(probes)} | "
                f"{s['p50_s']:.2f} / {s['p95_s']:.2f} | ${cost:.5f} |")
        out("")

    # Summarise
    summary_files = sorted(glob.glob(os.path.join(OUT_DIR, "summarise_*.csv")))
    if summary_files:
        out("## FR-01 summarisation groundedness (balanced 60 emails, spaCy NER)\n")
        out("| Model | Produced | Grounded | Claims checked / output | Failed outright | "
            "p50 / p95 s per call | USD per summary |")
        out("|---|---|---|---|---|---|---|")
        for path in summary_files:
            model, tag = os.path.basename(path)[len("summarise_"):-4].rsplit("_", 1)
            rows = _read_csv(path)
            produced = [r for r in rows if r["produced"] == "True"]
            grounded = sum(1 for r in produced if r["grounded"] == "True")
            claims = sum(int(r["claims_checked"] or 0) for r in produced)
            s = _call_stats(calls_for(model, "summarise", tag))
            cost = _cost(model, s["input_tokens"], s["output_tokens"]) / max(1, len(rows))
            per_op_cost[model]["summary"] = cost
            out(f"| {model} | {len(produced)}/{len(rows)} | {grounded}/{len(produced)} = "
                f"{grounded / max(1, len(produced)):.1%} | {claims / max(1, len(produced)):.1f} | "
                f"{len(rows) - len(produced)} | {s['p50_s']:.1f} / {s['p95_s']:.1f} | ${cost:.4f} |")
        out("")

    # Weekly cost
    out("## What a week would cost (assumed usage profile, measured unit costs)\n")
    out(f"Profile (an assumption, not a measurement): {WEEKLY_PROFILE['emails_classified']} emails "
        f"classified, {WEEKLY_PROFILE['summaries']} summaries, {WEEKLY_PROFILE['drafts']} drafts and "
        f"{WEEKLY_PROFILE['voice_commands']} voice commands per user per week. Drafts are priced "
        f"at the measured summary cost (similar input, similar output length). Budget: "
        f"${WEEKLY_BUDGET_USD:.2f}/week.\n")
    out("| Model | USD per user-week | Users inside $5/week |")
    out("|---|---|---|")
    for model in models:
        ops = per_op_cost.get(model, {})
        if not {"classify", "summary", "voice_command"} <= set(ops):
            continue
        week = (WEEKLY_PROFILE["emails_classified"] * ops["classify"]
                + (WEEKLY_PROFILE["summaries"] + WEEKLY_PROFILE["drafts"]) * ops["summary"]
                + WEEKLY_PROFILE["voice_commands"] * ops["voice_command"])
        out(f"| {model} | ${week:.3f} | {WEEKLY_BUDGET_USD / week:,.0f} |")
    out("")

    # Memory
    memory_path = os.path.join(OUT_DIR, "memory.json")
    if os.path.exists(memory_path):
        with open(memory_path, encoding="utf-8") as f:
            memory = json.load(f)
        out("## Client-side memory (fresh interpreter per SDK, median of 3)\n")
        out("| SDK | RSS added by import + client + one metadata call | Process RSS after | "
            "Import + first call |")
        out("|---|---|---|---|")
        for name, m in memory.items():
            out(f"| {name} | {m['delta_mb']:.1f} MB | {m['rss_after_mb']:.1f} MB | "
                f"{m['cold_start_s']:.2f} s |")
        out("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("task", choices=["classify", "intent", "summarise", "memory", "report"])
    parser.add_argument("--model")
    parser.add_argument("--split", default="dev,test", help="comma list of dev / test")
    parser.add_argument("--tag", default="r1")
    parser.add_argument("--limit", type=int, default=60)
    parser.add_argument("--out", default=None)
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--mask-ids", action="store_true",
                        help="send opaque ids instead of '<provenance>-<sha>'; run name <model>+maskedid")
    parser.add_argument("--batch-size", type=int, default=BATCH_SIZE)
    args = parser.parse_args()
    logging.basicConfig(level=logging.WARNING)
    os.makedirs(OUT_DIR, exist_ok=True)

    if args.task in ("classify", "intent", "summarise") and not args.model:
        sys.exit("--model is required")
    if args.task == "classify":
        for split in args.split.split(","):
            run_classify(args.model, split.strip(), args.tag, args.force,
                         batch_size=args.batch_size, mask_ids=args.mask_ids,
                         run_name=(f"{args.model}+maskedid" if args.mask_ids else None))
    elif args.task == "intent":
        run_intent(args.model, args.tag, args.force)
    elif args.task == "summarise":
        run_summarise(args.model, args.tag, args.limit, args.force)
    elif args.task == "memory":
        run_memory()
    else:
        text = build_report()
        print(text)
        if args.out:
            with open(args.out, "w", encoding="utf-8") as f:
                f.write(text + "\n")


if __name__ == "__main__":
    main()
