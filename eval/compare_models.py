def run_summarise(model, tag, limit, force):
    from eval.evaluate_grounding import _claims_checked, _load as load_grounding_rows, _run

    config = _config()
    out_csv = _path("summarise", model, tag)
    out_calls = _path("calls", model, "summarise", tag, ext="jsonl")
    _refuse_overwrite([out_csv, out_calls], force)

    rows = load_grounding_rows(DATASET, limit)
    adapter = providers.build(model)
    set_client(adapter)
    try:
        outputs, errors = _run("summarise", rows, config)
    finally:
        reset_client()
    saved = []
    for output in outputs:
        row = output["_row"]
        saved.append({"id": row["id"], "category": row["category"],
                      "text_origin": row["text_origin"], "produced": True,
                      "grounded": bool(output.get("grounded")),
                      "flag_count": len(output.get("ungrounded_flags", [])),
                      "claims_checked": _claims_checked(output),
                      "sentences": len(output.get("summary", [])),
                      "action_items": len(output.get("action_items", [])), "error": ""})
    for error in errors:
        saved.append({"id": error["id"], "category": error["category"], "text_origin": "",
                      "produced": False, "grounded": "", "flag_count": "",
                      "claims_checked": "", "sentences": "", "action_items": "",
                      "error": error["error"]})
    with open(out_csv, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(saved[0].keys()))
        writer.writeheader()
        writer.writerows(saved)
    _write_calls(out_calls, adapter.drain(), task="summarise", tag=tag,
                 settings=adapter.describe())
    produced = [r for r in saved if r["produced"]]
    grounded = sum(1 for r in produced if r["grounded"])
    print(f"{model} summarise {tag}: groundedness {grounded}/{len(produced)} "
          f"({grounded / max(1, len(produced)):.1%}), failed outright {len(errors)}")


