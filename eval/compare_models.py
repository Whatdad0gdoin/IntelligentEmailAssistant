"""Provider comparison: the project's own evaluations, run against other models.

    python -m eval.compare_models classify  --model claude-haiku-4-5 --split dev,test
    python -m eval.compare_models classify  --model claude-haiku-4-5 --split test --tag r2
    python -m eval.compare_models intent    --model claude-haiku-4-5
    python -m eval.compare_models summarise --model claude-haiku-4-5 --limit 60
    python -m eval.compare_models memory
    python -m eval.compare_models report    --out eval/data/compare/REPORT.md

WHAT IS HELD CONSTANT
Every run goes through the unchanged feature code -- classify_emails,
classify_intent, summarise_email -- with the same prompts, schemas, evidence
verifier, confidence threshold, preprocessing and scoring functions as
eval/evaluate_classifier.py, eval/intent_harness.py and
eval/evaluate_grounding.py. Classification uses the same row order and the same
batches of 20 as run 10 in eval/BENCHMARKS.md, because batch composition moves
the result (BENCHMARKS.md, "Run-to-run variance"). Only the model client is
swapped, through set_client(). eval/providers.py lists the settings that could
not be held constant (temperature, thinking) and why.

ONE MODEL PER PROCESS
set_client() is process-global, and one process per model also keeps one
provider's rate limiting out of another's latency figures. Run models as
separate processes, in parallel if you like.

NOTHING IS OVERWRITTEN
Every output path names the task, model, split and tag. A run that would write
to an existing path refuses unless --force is given: BENCHMARKS.md records a run
whose evidence was destroyed because a later run reused its path.

WHAT IS SAVED (eval/data/compare/)
    classify_<model>_<split>_<tag>.csv   one row per email: expected, predicted
                                         after verification, the model's RAW
                                         label and confidence before
                                         verification, and why it went to Review
    intent_<model>_<tag>.csv             one row per transcript
    summarise_<model>_<tag>.csv          one row per email: grounded, flags,
                                         claims checked, failure
    calls_<task>_<model>_<...>.jsonl     one record per model call: latency,
                                         attempts, tokens, outcome. Never any
                                         prompt or response text.
The report is computed from these files alone, with no model call, so every
figure in it can be regenerated by anyone holding the repository.
"""

