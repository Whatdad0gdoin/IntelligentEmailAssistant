"""Zero-cost accuracy experiments on the saved comparison runs.

    python -m eval.experiments.offline_analysis

No model is called. Everything is recomputed from the per-row files that
eval/compare_models.py saved in eval/data/compare/, so every figure printed
here can be regenerated by anyone with the repository.

PROTOCOL (the one eval/BENCHMARKS.md uses): every setting below is chosen on
the DEV split, frozen, and only then measured on TEST. Where a choice is made
by searching many candidates on dev, the size of that search is printed, so a
reader can judge how much selection pressure the test figure carries.

Four questions:

1. Is the 0.7 confidence threshold right for every model? It was tuned around
   gpt-4o-mini. A model whose confidence scale sits lower is not worse; it is
   being thrown away at the threshold.
2. Do ensembles of models beat the best single model?
3. Does a cheap-first cascade (ask a second model only when the first one
   abstains) recover accuracy at a fraction of the cost?
4. How much does any of this beat a classical TF-IDF model trained on dev?
"""

import collections
import csv
import glob
import itertools
import json
import os

from backend.orchestrator.schemas import CATEGORIES, REVIEW_CATEGORY
from eval import providers
from eval.compare_models import OUT_DIR, _mcnemar, _score, _wilson
from eval.evaluate_classifier import DATASET, _split_of

THRESHOLDS = [0.0, 0.3, 0.4, 0.5, 0.6, 0.7, 0.8, 0.9]
SHIPPED_THRESHOLD = 0.7
BASELINE = "gpt-4o-mini"
CHEAP_INPUT_PRICE = 1.00   # USD per 1M input tokens: "cheap" means at or below this


def load_runs(tag="r1"):
    """{model: {split: {id: row}}} for plain model runs (no '+variant')."""
    runs = collections.defaultdict(dict)
    for path in glob.glob(os.path.join(OUT_DIR, f"classify_*_*_{tag}.csv")):
        name = os.path.basename(path)[len("classify_"):-len(f"_{tag}.csv")]
        model, split = name.rsplit("_", 1)
        if "+" in model:
            continue
        with open(path, encoding="utf-8") as f:
            runs[model][split] = {r["id"]: r for r in csv.DictReader(f)}
    return runs


def verdict(row, threshold):
    """Rebuild the verifier's decision for one row at a given threshold."""
    raw = row["raw_category"]
    if raw not in CATEGORIES:
        return REVIEW_CATEGORY          # missing, failed call, or outside the enum
    if row["evidence_ok"] != "True":
        return REVIEW_CATEGORY          # the quote is not in the email
    try:
        confidence = max(0.0, min(1.0, float(row["raw_confidence"])))
    except (TypeError, ValueError):
        confidence = 0.0
    return raw if confidence >= threshold else REVIEW_CATEGORY


def metrics(pairs):
    m = _score(pairs)
    return m


def strict_of(labels, rows):
    return sum(labels[i] == rows[i]["expected"] for i in rows) / len(rows)


def fmt(m):
    return (f"{m['coverage']:.1%} | {m['accuracy']:.1%} | {m['strict']:.1%} | "
            f"{m['macro_f1']:.3f}")


def per_email_cost(model, split, tag="r1"):
    path = os.path.join(OUT_DIR, f"calls_{model}_classify_{split}_{tag}.jsonl")
    rows_path = os.path.join(OUT_DIR, f"classify_{model}_{split}_{tag}.csv")
    if not (os.path.exists(path) and os.path.exists(rows_path)):
        return None
    tokens_in = tokens_out = 0
    with open(path, encoding="utf-8") as f:
        for line in f:
            record = json.loads(line)
            tokens_in += record.get("input_tokens", 0)
            tokens_out += record.get("output_tokens", 0)
    with open(rows_path, encoding="utf-8") as f:
        n = sum(1 for _ in csv.DictReader(f))
    return providers.cost_usd(model, tokens_in, tokens_out) / n


def mcnemar_line(name, labels, rows, reference_labels):
    ids = list(rows)
    a = [reference_labels[i] == rows[i]["expected"] for i in ids]
    b = [labels[i] == rows[i]["expected"] for i in ids]
    only_ref, only_new, p = _mcnemar(a, b)
    return f"{name}: +{only_new} / -{only_ref} rows, p={p:.3f}"


def section_reconstruction(runs):
    print("\n## 1. Reconstruction check (threshold 0.7 rebuilt from raw answers)\n")
    bad = 0
    total = 0
    for model, splits in sorted(runs.items()):
        for split, rows in splits.items():
            for row in rows.values():
                total += 1
                if verdict(row, SHIPPED_THRESHOLD) != row["predicted"]:
                    bad += 1
    print(f"{total - bad}/{total} rows reproduce the saved verdict exactly; mismatches: {bad}.")
    return bad == 0


def section_thresholds(runs):
    print("\n## 2. Per-model confidence threshold, chosen on dev\n")
    print("| Model | Dev strict at 0.7 | Dev-chosen t | Dev strict at t | "
          "Test cov / acc / strict / F1 at 0.7 | Test at dev-chosen t | McNemar vs 0.7 on test |")
    print("|---|---|---|---|---|---|---|")
    chosen = {}
    for model in sorted(runs, key=lambda m: (m != BASELINE, m)):
        dev, test = runs[model].get("dev"), runs[model].get("test")
        if not dev or not test:
            continue
        scored = []
        for t in THRESHOLDS:
            m = metrics([(r["expected"], verdict(r, t)) for r in dev.values()])
            scored.append((m["strict"], m["accuracy"], t))
        best_strict, _, best_t = max(scored)
        chosen[model] = best_t
        dev07 = metrics([(r["expected"], verdict(r, SHIPPED_THRESHOLD)) for r in dev.values()])
        t07 = {i: verdict(r, SHIPPED_THRESHOLD) for i, r in test.items()}
        tch = {i: verdict(r, best_t) for i, r in test.items()}
        m07 = metrics([(test[i]["expected"], t07[i]) for i in test])
        mch = metrics([(test[i]["expected"], tch[i]) for i in test])
        print(f"| {model} | {dev07['strict']:.1%} | {best_t} | {best_strict:.1%} | {fmt(m07)} | "
              f"{fmt(mch)} | {mcnemar_line('', tch, test, t07).lstrip(': ')} |")
    print(f"\nSearch size: {len(THRESHOLDS)} thresholds per model, one choice per model, "
          "made on dev only.")

    print("\n### How often the evidence check discards a CORRECT label (test, r1)\n")
    print("| Model | Quote failed | ...of which the label was right | Share of the model's correct "
          "answers lost to the quote check |")
    print("|---|---|---|---|")
    for model in sorted(runs, key=lambda m: (m != BASELINE, m)):
        test = runs[model].get("test")
        if not test:
            continue
        failed = [r for r in test.values() if r["raw_category"] in CATEGORIES and r["evidence_ok"] != "True"]
        right = sum(r["raw_category"] == r["expected"] for r in failed)
        raw_right = sum(r["raw_category"] == r["expected"] for r in test.values())
        print(f"| {model} | {len(failed)} | {right} | {right / max(1, raw_right):.1%} |")
    return chosen


def labels_at(runs, model, split, thresholds=None):
    t = (thresholds or {}).get(model, SHIPPED_THRESHOLD)
    return {i: verdict(r, t) for i, r in runs[model][split].items()}


def vote(label_sets, ids, need):
    out = {}
    for i in ids:
        counts = collections.Counter(ls[i] for ls in label_sets if ls[i] != REVIEW_CATEGORY)
        if counts:
            label, n = counts.most_common(1)[0]
            tied = sum(1 for c in counts.values() if c == n) > 1
            out[i] = label if n >= need and not tied else REVIEW_CATEGORY
        else:
            out[i] = REVIEW_CATEGORY
    return out


def section_ensembles(runs, chosen):
    models = sorted(m for m in runs if "dev" in runs[m] and "test" in runs[m])
    dev_rows = runs[BASELINE]["dev"]
    test_rows = runs[BASELINE]["test"]
    baseline_test = labels_at(runs, BASELINE, "test")
    best_single_test = labels_at(runs, "gemini-3.8-flash", "test") if "gemini-3.8-flash" in runs else None
    cheap = [m for m in models if providers.PRICES[m][0] <= CHEAP_INPUT_PRICE]

    print("\n## 3. Ensembles, chosen on dev\n")
    for calibrated in (False, True):
        th = chosen if calibrated else None
        label = "dev-calibrated thresholds" if calibrated else "shipped threshold 0.7"
        for pool_name, pool in (("all models", models), ("cheap models only", cheap)):
            triples = list(itertools.combinations(pool, 3))
            best = None
            for triple in triples:
                dev_labels = vote([labels_at(runs, m, "dev", th) for m in triple], dev_rows, 2)
                s = strict_of(dev_labels, dev_rows)
                if best is None or s > best[0]:
                    best = (s, triple)
            s_dev, triple = best
            test_labels = vote([labels_at(runs, m, "test", th) for m in triple], test_rows, 2)
            m = metrics([(test_rows[i]["expected"], test_labels[i]) for i in test_rows])
            print(f"- Majority of 3, {label}, {pool_name} ({len(triples)} triples searched on dev): "
                  f"best = {' + '.join(triple)}; dev strict {s_dev:.1%}; TEST {fmt(m)}; "
                  f"{mcnemar_line('vs gpt-4o-mini', test_labels, test_rows, baseline_test)}"
                  + (f"; {mcnemar_line('vs gemini-3.8-flash', test_labels, test_rows, best_single_test)}"
                     if best_single_test else ""))

    print("\n### Agreement gate (accept only when two models agree), chosen on dev\n")
    pairs = list(itertools.combinations(models, 2))
    best = None
    for pair in pairs:
        dev_labels = vote([labels_at(runs, m, "dev") for m in pair], dev_rows, 2)
        md = metrics([(dev_rows[i]["expected"], dev_labels[i]) for i in dev_rows])
        key = (md["accuracy"], md["coverage"])
        if md["coverage"] >= 0.8 and (best is None or key > best[0]):
            best = (key, pair)
    if best:
        pair = best[1]
        test_labels = vote([labels_at(runs, m, "test") for m in pair], test_rows, 2)
        m = metrics([(test_rows[i]["expected"], test_labels[i]) for i in test_rows])
        print(f"Best pair by dev accuracy-on-covered with coverage >= 80% ({len(pairs)} pairs searched): "
              f"{' + '.join(pair)}; TEST {fmt(m)} (coverage | accuracy | strict | F1)")

    print("\n## 4. Cascade: model A, and model B only when A abstains (test, shipped threshold)\n")
    print("| A | B | Escalated | Test strict | Cost per 1,000 emails (USD) | vs A alone |")
    print("|---|---|---|---|---|---|")
    for a in [BASELINE] + [m for m in cheap if m != BASELINE]:
        # B chosen on dev: the model that maximises dev strict as the fallback for A.
        dev_a = labels_at(runs, a, "dev")
        best_b, best_s = None, -1
        for b in models:
            if b == a:
                continue
            dev_b = labels_at(runs, b, "dev")
            merged = {i: (dev_a[i] if dev_a[i] != REVIEW_CATEGORY else dev_b[i]) for i in dev_rows}
            s = strict_of(merged, dev_rows)
            if s > best_s:
                best_b, best_s = b, s
        test_a = labels_at(runs, a, "test")
        test_b = labels_at(runs, best_b, "test")
        merged = {i: (test_a[i] if test_a[i] != REVIEW_CATEGORY else test_b[i]) for i in test_rows}
        escalated = sum(1 for i in test_rows if test_a[i] == REVIEW_CATEGORY) / len(test_rows)
        cost = (per_email_cost(a, "test") or 0) + escalated * (per_email_cost(best_b, "test") or 0)
        print(f"| {a} | {best_b} | {escalated:.1%} | {strict_of(merged, test_rows):.1%} | "
              f"${cost * 1000:.3f} | {mcnemar_line('', merged, test_rows, test_a).lstrip(': ')} |")
    print("\nCascade cost treats the fallback as if priced per email at its batched rate; a real "
          "fallback call carries the system prompt alone, so this understates it slightly.")


def section_tfidf(runs):
    print("\n## 5. Classical baseline: TF-IDF + logistic regression trained on dev only\n")
    try:
        from sklearn.feature_extraction.text import TfidfVectorizer
        from sklearn.linear_model import LogisticRegression
        from sklearn.model_selection import StratifiedKFold, cross_val_score
        from sklearn.pipeline import make_pipeline
    except ImportError:
        print("scikit-learn is not installed; skipped.")
        return
    from backend.orchestrator.preprocess import preprocess

    with open(DATASET, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    def text(r):
        return f"{r.get('sender', '')} {r['subject']} {preprocess(r['body'], 12000).text}"

    dev = [r for r in rows if _split_of(r["id"]) == "dev"]
    test = [r for r in rows if _split_of(r["id"]) == "test"]
    best_c, best_cv = None, -1
    for c in (0.3, 1.0, 3.0, 10.0, 30.0):
        pipe = make_pipeline(TfidfVectorizer(ngram_range=(1, 2), sublinear_tf=True, min_df=1),
                             LogisticRegression(C=c, max_iter=5000))
        cv = cross_val_score(pipe, [text(r) for r in dev], [r["category"] for r in dev],
                             cv=StratifiedKFold(5, shuffle=True, random_state=20261006)).mean()
        if cv > best_cv:
            best_c, best_cv = c, cv
    pipe = make_pipeline(TfidfVectorizer(ngram_range=(1, 2), sublinear_tf=True, min_df=1),
                         LogisticRegression(C=best_c, max_iter=5000))
    pipe.fit([text(r) for r in dev], [r["category"] for r in dev])
    predicted = dict(zip([r["id"] for r in test], pipe.predict([text(r) for r in test])))
    m = metrics([(r["category"], predicted[r["id"]]) for r in test])
    real = metrics([(r["category"], predicted[r["id"]]) for r in test if r["text_origin"] == "real"])
    print(f"C chosen by 5-fold CV on dev: {best_c} (dev CV accuracy {best_cv:.1%}). "
          f"TEST (no abstention, so coverage 100%): accuracy {m['accuracy']:.1%}, macro-F1 "
          f"{m['macro_f1']:.3f}; real email only {real['accuracy']:.1%}.")
    for label, stats in m["per_class"].items():
        print(f"  {label:11} precision {stats['precision']:.1%}  recall {stats['recall']:.1%}")

    test_rows = runs[BASELINE]["test"]
    for model in (BASELINE, "gemini-3.8-flash", "claude-sonnet-5-5"):
        if model not in runs:
            continue
        llm = labels_at(runs, model, "test")
        hybrid = {i: (llm[i] if llm[i] != REVIEW_CATEGORY else predicted[i]) for i in test_rows}
        print(f"- Hybrid {model} -> TF-IDF when Review: TEST strict {strict_of(hybrid, test_rows):.1%} "
              f"(model alone {strict_of(llm, test_rows):.1%}); "
              f"{mcnemar_line('vs model alone', hybrid, test_rows, llm)}")


def main():
    runs = load_runs("r1")
    print(f"# Offline accuracy experiments (models: {', '.join(sorted(runs))})")
    section_reconstruction(runs)
    chosen = section_thresholds(runs)
    section_ensembles(runs, chosen)
    section_tfidf(runs)


if __name__ == "__main__":
    main()
